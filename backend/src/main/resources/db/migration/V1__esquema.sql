-- =====================================================================
-- Conecta Educação SLZ — esquema principal
-- SQL portável (PostgreSQL e H2 em modo PostgreSQL, usado nos testes).
-- =====================================================================

-- ---------- Território e rede ----------------------------------------
-- Territórios são AGRUPAMENTOS DEMONSTRATIVOS de bairros, não divisões
-- administrativas oficiais da SEMED. Não há limites geográficos (polígonos):
-- lat/lng é apenas o centróide das escolas fictícias do agrupamento.
CREATE TABLE territorio (
    id          VARCHAR(20)  PRIMARY KEY,
    nome        VARCHAR(120) NOT NULL,
    descricao   VARCHAR(500),
    bairros     VARCHAR(300)
);

CREATE TABLE escola (
    id            VARCHAR(20)  PRIMARY KEY,
    nome          VARCHAR(160) NOT NULL,
    territorio_id VARCHAR(20)  NOT NULL REFERENCES territorio(id),
    bairro        VARCHAR(120) NOT NULL,
    lat           DOUBLE PRECISION NOT NULL,
    lng           DOUBLE PRECISION NOT NULL,
    etapas        VARCHAR(120) NOT NULL
);
CREATE INDEX ix_escola_territorio ON escola(territorio_id);

CREATE TABLE professor (
    id    VARCHAR(20)  PRIMARY KEY,
    nome  VARCHAR(120) NOT NULL,
    escola_id VARCHAR(20) NOT NULL REFERENCES escola(id)
);

CREATE TABLE componente (
    id    VARCHAR(10)  PRIMARY KEY,
    nome  VARCHAR(80)  NOT NULL
);

CREATE TABLE turma (
    id            VARCHAR(30) PRIMARY KEY,
    escola_id     VARCHAR(20) NOT NULL REFERENCES escola(id),
    ano_escolar   INTEGER     NOT NULL,
    nome          VARCHAR(40) NOT NULL,
    turno         VARCHAR(20) NOT NULL,
    ano_letivo    INTEGER     NOT NULL
);
CREATE INDEX ix_turma_escola ON turma(escola_id);

-- Vínculo docente-turma por componente (anos iniciais: polivalente nos dois componentes)
CREATE TABLE professor_turma (
    professor_id  VARCHAR(20) NOT NULL REFERENCES professor(id),
    turma_id      VARCHAR(30) NOT NULL REFERENCES turma(id),
    componente_id VARCHAR(10) NOT NULL REFERENCES componente(id),
    PRIMARY KEY (professor_id, turma_id, componente_id)
);

-- Minimização de dados: apenas nome fictício abreviado e código.
CREATE TABLE estudante (
    id            VARCHAR(20) PRIMARY KEY,
    codigo        VARCHAR(20) NOT NULL UNIQUE,
    nome          VARCHAR(80) NOT NULL,
    turma_id      VARCHAR(30) NOT NULL REFERENCES turma(id)
);
CREATE INDEX ix_estudante_turma ON estudante(turma_id);

-- ---------- Currículo ------------------------------------------------
CREATE TABLE habilidade (
    id               VARCHAR(20)  PRIMARY KEY,          -- código BNCC
    componente_id    VARCHAR(10)  NOT NULL REFERENCES componente(id),
    ano_escolar      INTEGER      NOT NULL,             -- ano em que é analisada nesta demonstração
    anos_bncc        VARCHAR(40)  NOT NULL,             -- faixa indicada no código (ex.: 3º ao 5º)
    descricao        VARCHAR(1000) NOT NULL,
    unidade_tematica VARCHAR(160),
    grupo            VARCHAR(80)  NOT NULL,             -- agrupamento pedagógico usado nas análises (ex.: Frações)
    fonte            VARCHAR(160) NOT NULL
);

-- Matriz de referência das avaliações (descritores) — DEMONSTRATIVA
CREATE TABLE descritor (
    id            VARCHAR(20)  PRIMARY KEY,
    componente_id VARCHAR(10)  NOT NULL REFERENCES componente(id),
    ano_escolar   INTEGER      NOT NULL,
    descricao     VARCHAR(500) NOT NULL,
    matriz        VARCHAR(60)  NOT NULL
);

-- Mapeamento EXPLÍCITO descritor -> habilidade. Nada é tratado como equivalente
-- sem um registro aqui. status_validacao indica se houve validação técnica.
CREATE TABLE descritor_habilidade (
    descritor_id     VARCHAR(20) NOT NULL REFERENCES descritor(id),
    habilidade_id    VARCHAR(20) NOT NULL REFERENCES habilidade(id),
    status_validacao VARCHAR(20) NOT NULL,              -- DEMONSTRATIVO | VALIDADO
    observacao       VARCHAR(300),
    PRIMARY KEY (descritor_id, habilidade_id)
);

-- ---------- Avaliação ------------------------------------------------
CREATE TABLE avaliacao (
    id                    VARCHAR(20)  PRIMARY KEY,
    sigla                 VARCHAR(20)  NOT NULL,
    nome                  VARCHAR(160) NOT NULL,
    tipo                  VARCHAR(30)  NOT NULL,       -- DIAGNOSTICA_REDE | FORMATIVA_REDE | REAVALIACAO_DIRECIONADA
    data_aplicacao        DATE         NOT NULL,
    ano_letivo            INTEGER      NOT NULL,
    matriz                VARCHAR(60)  NOT NULL,
    grupo_comparabilidade VARCHAR(60)               -- avaliações só são comparadas dentro do mesmo grupo
);

-- Resultado por estudante x avaliação x descritor, com o contexto pedagógico
-- (turma) no momento da aplicação.
CREATE TABLE resultado (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    avaliacao_id  VARCHAR(20) NOT NULL REFERENCES avaliacao(id),
    estudante_id  VARCHAR(20) NOT NULL REFERENCES estudante(id),
    turma_id      VARCHAR(30) NOT NULL REFERENCES turma(id),
    descritor_id  VARCHAR(20) NOT NULL REFERENCES descritor(id),
    acertos       INTEGER     NOT NULL,
    itens         INTEGER     NOT NULL,
    registrado_por VARCHAR(40),
    registrado_em TIMESTAMP,
    CONSTRAINT ck_resultado_acertos CHECK (acertos >= 0 AND itens > 0 AND acertos <= itens),
    CONSTRAINT uq_resultado UNIQUE (avaliacao_id, estudante_id, descritor_id)
);
CREATE INDEX ix_resultado_turma ON resultado(turma_id, avaliacao_id);
CREATE INDEX ix_resultado_estudante ON resultado(estudante_id);

-- ---------- Usuários e acesso ----------------------------------------
CREATE TABLE usuario (
    id            VARCHAR(20)  PRIMARY KEY,
    email         VARCHAR(120) NOT NULL UNIQUE,
    nome          VARCHAR(120) NOT NULL,
    senha_hash    VARCHAR(100) NOT NULL,
    papel         VARCHAR(20)  NOT NULL,              -- GESTOR_REDE | COORDENADOR | PROFESSOR
    cargo         VARCHAR(120) NOT NULL,
    escola_id     VARCHAR(20)  REFERENCES escola(id),
    professor_id  VARCHAR(20)  REFERENCES professor(id),
    ativo         BOOLEAN      NOT NULL,
    destaque      BOOLEAN      NOT NULL DEFAULT FALSE  -- perfis exibidos na tela de entrada da demonstração
);

-- ---------- Estratégias pedagógicas (catálogo do motor de regras) ----
CREATE TABLE estrategia (
    id                VARCHAR(20)  PRIMARY KEY,
    titulo            VARCHAR(160) NOT NULL,
    tipo              VARCHAR(40)  NOT NULL,
    nivel             VARCHAR(20)  NOT NULL,          -- INDIVIDUAL | TURMA | AMBOS
    objetivo          VARCHAR(600) NOT NULL,
    como_aplicar      VARCHAR(2000) NOT NULL,         -- passos separados por '|'
    materiais         VARCHAR(600),
    como_acompanhar   VARCHAR(800) NOT NULL,
    quando_reavaliar  VARCHAR(400) NOT NULL,
    duracao_semanas   INTEGER      NOT NULL,
    perfil_indicado   VARCHAR(20)  NOT NULL           -- ATENCAO | DESENVOLVIMENTO | TODOS
);

CREATE TABLE estrategia_habilidade (
    estrategia_id VARCHAR(20) NOT NULL REFERENCES estrategia(id),
    habilidade_id VARCHAR(20) NOT NULL REFERENCES habilidade(id),
    PRIMARY KEY (estrategia_id, habilidade_id)
);

-- ---------- Formação continuada --------------------------------------
CREATE TABLE formacao (
    id            VARCHAR(20)  PRIMARY KEY,
    titulo        VARCHAR(200) NOT NULL,
    descricao     VARCHAR(1000) NOT NULL,
    objetivos     VARCHAR(1000) NOT NULL,
    modalidade    VARCHAR(30)  NOT NULL,
    carga_horaria INTEGER      NOT NULL,
    publico       VARCHAR(200) NOT NULL,
    data_inicio   DATE         NOT NULL,
    data_fim      DATE         NOT NULL,
    vagas         INTEGER      NOT NULL,
    status        VARCHAR(20)  NOT NULL               -- INSCRICOES | EM_CURSO | CONCLUIDA
);

CREATE TABLE formacao_habilidade (
    formacao_id   VARCHAR(20) NOT NULL REFERENCES formacao(id),
    habilidade_id VARCHAR(20) NOT NULL REFERENCES habilidade(id),
    PRIMARY KEY (formacao_id, habilidade_id)
);

CREATE TABLE participacao (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    formacao_id         VARCHAR(20) NOT NULL REFERENCES formacao(id),
    professor_id        VARCHAR(20) NOT NULL REFERENCES professor(id),
    status              VARCHAR(20) NOT NULL,         -- INSCRITO | CONCLUIDO
    aplicou_estrategia  BOOLEAN,
    registro_aplicacao  VARCHAR(1000),
    atualizado_em       TIMESTAMP   NOT NULL,
    CONSTRAINT uq_participacao UNIQUE (formacao_id, professor_id)
);

-- ---------- Plano de Ação Pedagógica ---------------------------------
CREATE TABLE plano (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    escopo                   VARCHAR(20)  NOT NULL,    -- TERRITORIO | ESCOLA | TURMA | ESTUDANTE
    territorio_id            VARCHAR(20)  REFERENCES territorio(id),
    escola_id                VARCHAR(20)  REFERENCES escola(id),
    turma_id                 VARCHAR(30)  REFERENCES turma(id),
    estudante_id             VARCHAR(20)  REFERENCES estudante(id),
    plano_pai_id             BIGINT       REFERENCES plano(id),
    componente_id            VARCHAR(10)  REFERENCES componente(id),
    titulo                   VARCHAR(200) NOT NULL,
    problema                 VARCHAR(1500) NOT NULL,
    evidencias               VARCHAR(2000) NOT NULL,
    objetivo                 VARCHAR(1000) NOT NULL,
    publico_alvo             VARCHAR(300) NOT NULL,
    estrategia               VARCHAR(2000) NOT NULL,
    estrategia_id            VARCHAR(20)  REFERENCES estrategia(id),
    formacao_id              VARCHAR(20)  REFERENCES formacao(id),
    responsavel              VARCHAR(160) NOT NULL,
    data_inicio              DATE         NOT NULL,
    prazo                    DATE         NOT NULL,
    indicador_acompanhamento VARCHAR(600) NOT NULL,
    criterio_conclusao       VARCHAR(600) NOT NULL,
    resultado_esperado       VARCHAR(600) NOT NULL,
    status                   VARCHAR(20)  NOT NULL,    -- PLANEJADO | EM_ANDAMENTO | CONCLUIDO | REAVALIADO
    resultado_observado      VARCHAR(1500),
    decisao_reavaliacao      VARCHAR(20),              -- FUNCIONOU | AJUSTAR | SUBSTITUIR
    avaliacao_base_id        VARCHAR(20)  REFERENCES avaliacao(id),
    recomendacao_chave       VARCHAR(160),
    criado_por               VARCHAR(20)  NOT NULL REFERENCES usuario(id),
    criado_em                TIMESTAMP    NOT NULL,
    atualizado_em            TIMESTAMP    NOT NULL,
    versao                   INTEGER      NOT NULL,
    CONSTRAINT ck_plano_prazo CHECK (prazo >= data_inicio)
);
CREATE INDEX ix_plano_escola ON plano(escola_id);
CREATE INDEX ix_plano_turma ON plano(turma_id);
CREATE INDEX ix_plano_estudante ON plano(estudante_id);

CREATE TABLE plano_habilidade (
    plano_id      BIGINT      NOT NULL REFERENCES plano(id),
    habilidade_id VARCHAR(20) NOT NULL REFERENCES habilidade(id),
    PRIMARY KEY (plano_id, habilidade_id)
);

CREATE TABLE plano_acao (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plano_id      BIGINT       NOT NULL REFERENCES plano(id),
    descricao     VARCHAR(600) NOT NULL,
    responsavel   VARCHAR(160) NOT NULL,
    data_prevista DATE         NOT NULL,
    status        VARCHAR(20)  NOT NULL,              -- PENDENTE | EM_ANDAMENTO | CONCLUIDA
    concluida_em  DATE
);

-- Registros de execução/acompanhamento
CREATE TABLE plano_registro (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plano_id      BIGINT        NOT NULL REFERENCES plano(id),
    tipo          VARCHAR(20)   NOT NULL,             -- EXECUCAO | ACOMPANHAMENTO | REAVALIACAO
    data          DATE          NOT NULL,
    descricao     VARCHAR(1500) NOT NULL,
    percepcao     VARCHAR(20),                        -- AVANCO | ESTAVEL | DIFICULDADE
    autor_id      VARCHAR(20)   NOT NULL REFERENCES usuario(id),
    criado_em     TIMESTAMP     NOT NULL
);

-- Histórico de alterações (auditoria funcional do plano)
CREATE TABLE plano_historico (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plano_id      BIGINT        NOT NULL REFERENCES plano(id),
    data_hora     TIMESTAMP     NOT NULL,
    usuario_id    VARCHAR(20)   NOT NULL REFERENCES usuario(id),
    tipo          VARCHAR(20)   NOT NULL,             -- CRIACAO | EDICAO | STATUS | REAVALIACAO
    status_de     VARCHAR(20),
    status_para   VARCHAR(20),
    justificativa VARCHAR(1000),
    alteracoes    VARCHAR(2000)
);

-- ---------- Recomendações: validação humana ---------------------------
CREATE TABLE recomendacao_decisao (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chave         VARCHAR(160)  NOT NULL,
    decisao       VARCHAR(20)   NOT NULL,             -- ACEITA | DESCARTADA
    justificativa VARCHAR(1000),
    plano_id      BIGINT        REFERENCES plano(id),
    usuario_id    VARCHAR(20)   NOT NULL REFERENCES usuario(id),
    data_hora     TIMESTAMP     NOT NULL
);
CREATE INDEX ix_recomendacao_chave ON recomendacao_decisao(chave);

-- ---------- Auditoria de acessos e alterações -------------------------
CREATE TABLE auditoria (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_hora   TIMESTAMP    NOT NULL,
    usuario_id  VARCHAR(20)  NOT NULL,
    papel       VARCHAR(20)  NOT NULL,
    acao        VARCHAR(40)  NOT NULL,
    recurso     VARCHAR(40)  NOT NULL,
    recurso_id  VARCHAR(60),
    permitido   BOOLEAN      NOT NULL,
    detalhe     VARCHAR(500)
);
CREATE INDEX ix_auditoria_data ON auditoria(data_hora);
